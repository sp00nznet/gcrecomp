// ppc-diff generator: turns a vectors file (tools/ppc-diff/gen_vectors.py) into C++ with the recompiler's own
// emitter: one function per case that runs the case's instructions, plus a table with the inputs and the expected
// outputs. ppc_diff_run compiles that table in and compares. Programs with branches are skipped (the emitter needs a
// function context for them) and counted.
//
// usage: ppc_diff_gen VECTORS OUT.inc
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>
#include <sstream>
#include <string>
#include <vector>

#include "gcrecomp/ppc.h"
#include "gcrecomp/ppc_to_c.h"

using namespace gcrecomp;

static std::vector<std::string> split(const std::string& s, char sep) {
    std::vector<std::string> v;
    std::string cur;
    for (char c : s) {
        if (c == sep) {
            v.push_back(cur);
            cur.clear();
        } else {
            cur += c;
        }
    }
    v.push_back(cur);
    return v;
}

// "K.I=HEX K.I=HEX ..." -> C++ initialiser rows.
static void entries(FILE* out, const std::string& text, const std::string& name) {
    std::fprintf(out, "static const PdEntry %s[] = {", name.c_str());
    std::istringstream is(text);
    std::string tok;
    while (is >> tok) {
        unsigned kind = 0, idx = 0;
        unsigned long long v = 0;
        if (std::sscanf(tok.c_str(), "%u.%u=%llx", &kind, &idx, &v) != 3) {
            std::fprintf(stderr, "bad entry '%s'\n", tok.c_str());
            std::exit(1);
        }
        std::fprintf(out, "{%u,%u,0x%llxull},", kind, idx, v);
    }
    std::fprintf(out, "{255,0,0}};\n");
}

int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: ppc_diff_gen VECTORS OUT.inc\n");
        return 2;
    }
    std::ifstream in(argv[1]);
    if (!in) {
        std::fprintf(stderr, "cannot open %s\n", argv[1]);
        return 1;
    }
    FILE* out = std::fopen(argv[2], "w");
    if (!out) return 1;
    std::fprintf(out, "// Generated by ppc_diff_gen from %s; do not edit.\n", argv[1]);

    std::string table;
    std::string line;
    int n = 0, skipped_branch = 0, skipped_unknown = 0;
    std::map<std::string, int> unknown;
    while (std::getline(in, line)) {
        if (line.empty() || line[0] == '#') continue;
        const auto parts = split(line, '|');
        if (parts.size() != 3) {
            std::fprintf(stderr, "bad line: %s\n", line.c_str());
            return 1;
        }
        char name[64];
        int flags = 0;
        char words_txt[2048];
        if (std::sscanf(parts[0].c_str(), "case %63s %d %2047s", name, &flags, words_txt) != 3) {
            std::fprintf(stderr, "bad header: %s\n", parts[0].c_str());
            return 1;
        }
        std::vector<PPCInsn> insns;
        bool skip_branch = false, skip_unknown = false;
        const auto words = split(words_txt, ',');
        for (size_t i = 0; i + 1 < words.size(); ++i) {  // the last word is blr, not executed
            const uint32_t w = static_cast<uint32_t>(std::strtoul(words[i].c_str(), nullptr, 16));
            PPCInsn insn = ppc_disasm(w, 0x80003100u + 4 * static_cast<uint32_t>(i));
            if (insn.type == PPCInsnType::UNKNOWN) {
                skip_unknown = true;
                ++unknown[insn.mnemonic + " " + words[i]];
                break;
            }
            if (insn.is_branch()) skip_branch = true;
            insns.push_back(insn);
        }
        if (skip_unknown) {
            ++skipped_unknown;
            continue;
        }
        if (skip_branch) {
            ++skipped_branch;
            continue;
        }
        std::fprintf(out, "static void pd_fn_%d(PPCContext* ctx, Memory* mem) {\n", n);
        PPCToCEmitter emitter(out);
        std::string dis;
        for (const PPCInsn& insn : insns) {
            std::fprintf(out, "  {\n");
            emitter.emit_insn(insn);
            std::fprintf(out, "  }\n");
            if (!dis.empty()) dis += "; ";
            dis += insn.mnemonic;
        }
        std::fprintf(out, "}\n");
        entries(out, parts[1], "pd_in_" + std::to_string(n));
        entries(out, parts[2], "pd_out_" + std::to_string(n));
        table += "  {\"" + std::string(name) + "\", " + std::to_string(flags) + ", \"" + words_txt + "\", \"" + dis +
                 "\", pd_fn_" + std::to_string(n) + ", pd_in_" + std::to_string(n) + ", pd_out_" + std::to_string(n) +
                 "},\n";
        ++n;
    }
    std::fprintf(out, "static const PdCase pd_cases[] = {\n%s};\n", table.c_str());
    std::fprintf(out, "static const int pd_ncases = %d;\n", n);
    std::fprintf(out, "static const int pd_skipped_branch = %d;\n", skipped_branch);
    std::fprintf(out, "static const int pd_skipped_unknown = %d;\n", skipped_unknown);
    std::fclose(out);
    for (const auto& u : unknown)
        std::fprintf(stderr, "ppc_diff_gen: %s: %d case(s) skipped, the instruction does not decode\n", u.first.c_str(), u.second);
    std::fprintf(stderr, "ppc_diff_gen: %d cases (%d with a branch and %d with an undecodable instruction skipped)\n", n,
                 skipped_branch, skipped_unknown);
    return 0;
}
